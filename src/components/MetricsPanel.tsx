/** Most recent aggregate value for a metric name. */
function latestValue(metrics: readonly MetricSnapshot[], name: string): number | null {
  const metric = metrics.find((m) => m.name === name)
  if (!metric || metric.points.length === 0) return null

  if (metric.type === 'histogram') {
    let sum = 0
    let count = 0
    for (const point of metric.points) {
      sum += point.sum ?? 0
      count += point.count ?? 0
    }
    return count > 0 ? sum / count : null
  }
  return metric.points.reduce((total, point) => total + (point.value ?? 0), 0)
}

